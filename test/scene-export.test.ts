import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import {
	normalizeSceneDsl,
	renderSceneDsl,
	type SceneSpec,
	sceneDocumentSchema,
	sceneJsonSchema,
	sceneToBlenderScript,
	sceneToJson,
	solveScene,
} from "../src/index.js";
import { sceneSource } from "./support/scene-files.js";

const FIXTURES = [
	"study",
	"study-pinned",
	"study-broken",
	"meeting",
	"showroom",
	"study-paths",
	"office",
	"storeroom",
	"park",
];
const source = sceneSource;

describe("dge-scene export", () => {
	it("matches the published JSON Schema", () => {
		const published = JSON.parse(
			readFileSync("schema/dge-scene.v1.schema.json", "utf8"),
		);
		expect(published).toEqual(sceneJsonSchema());
	});

	it.each(FIXTURES)("%s validates against the contract", (name) => {
		const result = renderSceneDsl(source(name));
		expect(result.format).toBe("scene-json");
		const document = JSON.parse(result.content ?? "");
		expect(() => sceneDocumentSchema.parse(document)).not.toThrow();
		expect(document.valid).toBe(name !== "study-broken");
	});

	it("keeps number arrays on one line", () => {
		const content = renderSceneDsl(source("study")).content ?? "";
		expect(content).toContain('"position": [2, 4.65, 0]');
		expect(content).toContain('"quaternion": [0, 0, 1, 0]');
	});

	it("embeds the document in the Blender script", () => {
		const script = renderSceneDsl(source("study"), { format: "blender" });
		const content = script.content ?? "";
		expect(content).toMatch(/^# Generated by auto-graph/);
		expect(content).toContain("import bpy");
		const literal = /^DATA = json\.loads\((.*)\)$/m.exec(content)?.[1] ?? "";
		expect(JSON.parse(JSON.parse(literal))).toEqual(
			JSON.parse(renderSceneDsl(source("study")).content ?? ""),
		);
	});

	it("rejects unknown formats", () => {
		expect(
			renderSceneDsl(source("study"), { format: "png" }).diagnostics[0],
		).toMatchObject({ code: "export.scene.format" });
	});

	// Builds every fixture in Blender and compares the world boxes and turns
	// with the JSON. Needs a Python with the bpy module (pip install bpy):
	// DGE_BLENDER_PYTHON=/path/to/python npx vitest run test/scene-export.test.ts
	const python = process.env.DGE_BLENDER_PYTHON;
	it.skipIf(python === undefined).each(FIXTURES)(
		"%s builds in Blender exactly as solved",
		(name) => {
			const dir = mkdtempSync(join(tmpdir(), "dge-scene-"));
			try {
				const script = join(dir, "scene.py");
				const json = join(dir, "scene.json");
				writeFileSync(
					script,
					renderSceneDsl(source(name), { format: "blender" }).content ?? "",
				);
				writeFileSync(json, renderSceneDsl(source(name)).content ?? "");
				const output = execFileSync(
					python as string,
					[
						new URL("./support/blender_check.py", import.meta.url).pathname,
						script,
						json,
					],
					{ encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] },
				);
				const result = JSON.parse(output.trim().split("\n").at(-1) ?? "{}");
				expect(result.problems).toEqual([]);
				expect(result.objects).toBeGreaterThan(0);
				const document = JSON.parse(readFileSync(json, "utf8"));
				expect(result.paths).toBe(document.paths.length);
				expect(result.openings).toBe(document.openings.length);
			} finally {
				rmSync(dir, { recursive: true, force: true });
			}
		},
		120_000,
	);
});

// A walk late in the day still fits Blender's frames: the timeline starts
// when the first agent sets off.
describe("Blender timeline", () => {
	const python = process.env.DGE_BLENDER_PYTHON;
	it.skipIf(python === undefined)(
		"keys agents that set off 50,000 s in",
		() => {
			const yaml = [
				"scene: late",
				"bounds: { width: 8, depth: 4, height: 2.5 }",
				"objects: {}",
				"openings:",
				"  w: { wall: west, at: 1, width: 1 }",
				"  e: { wall: east, at: 1, width: 1 }",
				"  w2: { wall: west, at: 3, width: 1 }",
				"  e2: { wall: east, at: 3, width: 1 }",
				"paths:",
				"  - person from w to e, start 50000",
				"  - person from w2 to e2, start 50003.3333",
			].join("\n");
			const dir = mkdtempSync(join(tmpdir(), "dge-scene-"));
			try {
				const script = join(dir, "scene.py");
				const json = join(dir, "scene.json");
				writeFileSync(
					script,
					renderSceneDsl(yaml, { format: "blender" }).content ?? "",
				);
				writeFileSync(json, renderSceneDsl(yaml).content ?? "");
				const output = execFileSync(
					python as string,
					[
						new URL("./support/blender_check.py", import.meta.url).pathname,
						script,
						json,
					],
					{ encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] },
				);
				const result = JSON.parse(output.trim().split("\n").at(-1) ?? "{}");
				expect(result.problems).toEqual([]);
				expect(result.corners).toBe(4);
			} finally {
				rmSync(dir, { recursive: true, force: true });
			}
		},
		120_000,
	);
});

// #130: geometry that overflows is left out (listed as unplaced), so every
// document written is a valid dge-scene v1 document.
describe("dge-scene export of overflowing geometry", () => {
	it.each([
		[
			"stacked heights",
			{
				bounds: { width: 10, depth: 10 },
				objects: {
					a: { size: [1, 1, 1e308], position: [3, 3] },
					b: { size: [1, 1, 1e308] },
				},
				relations: ["b on a"],
			},
		],
		[
			"huge bounds",
			{
				bounds: { width: 1e308, depth: 1e308 },
				objects: { a: { size: [1, 1, 1] } },
			},
		],
	])("keeps the document valid with %s", (_, value) => {
		const normalized = normalizeSceneDsl({ scene: "numeric", ...value });
		const solved = solveScene(normalized.scene as SceneSpec);
		const document = JSON.parse(sceneToJson(solved));
		expect(() => sceneDocumentSchema.parse(document)).not.toThrow();
		expect(JSON.stringify(document)).not.toMatch(/null/);
		const script = sceneToBlenderScript(solved);
		expect(script).not.toMatch(/null|NaN|Infinity/);
		if (!solved.valid) {
			expect(document.unplaced.length).toBeGreaterThan(0);
			expect(solved.diagnostics.map((d) => d.code)).toContain(
				"scene.non-finite",
			);
		}
	});
});
