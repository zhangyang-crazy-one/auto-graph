import { readFileSync, writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { renderDiagramDsl } from "../../src/dsl/index.js";
import type { CoordinatedDiagram } from "../../src/ir/index.js";
import {
	containmentRelations,
	LAYOUT_METRIC_HARD_KEYS,
	type LayoutMetrics,
	measureLayoutQuality,
} from "../../src/quality/index.js";
import { DeterministicTextMeasurer } from "../../src/text/index.js";
import { generateSyntheticDsl } from "../support/synthetic.js";
import { layoutWithElk } from "./elk-adapter.js";

/**
 * DGE versus ELK layered on identical input (plan phase 1d).
 *
 * Opt-in: DGE_ELK=1 npx vitest run test/benchmark/elk-comparison.test.ts
 * writes test/fixtures/benchmark/elk-comparison.md.
 */
const enabled = process.env.DGE_ELK === "1";
const REPO_ROOT = new URL("../../", import.meta.url);
const REPORT_URL = new URL(
	"../fixtures/benchmark/elk-comparison.md",
	import.meta.url,
);

const FIXTURES = [
	"test/fixtures/benchmark/cn-swimlane.yaml",
	"test/fixtures/benchmark/cn-vertical-lanes.yaml",
	"test/fixtures/benchmark/cn-architecture.yaml",
	"test/fixtures/benchmark/cn-long-flow.yaml",
	"test/fixtures/issue-13/microservice.auto-graph.yaml",
	"test/fixtures/phase-08/contract-swimlane.auto-graph.yaml",
	"examples/fan-out.yaml",
	"examples/swimlane.yaml",
	"examples/flowchart.yaml",
	"examples/groups.yaml",
];
const SYNTHETIC_SIZES = (process.env.DGE_ELK_SIZES ?? "50,100,300")
	.split(",")
	.map(Number);
const KINDS = ["plain", "architecture", "process"] as const;

interface Case {
	name: string;
	source: string;
}

function cases(): Case[] {
	return [
		...FIXTURES.map((path) => ({
			name: path.replace(/^.*\//, "").replace(/\.yaml$/, ""),
			source: readFileSync(new URL(path, REPO_ROOT), "utf8"),
		})),
		...KINDS.flatMap((kind) =>
			SYNTHETIC_SIZES.map((nodes) => ({
				name: `synthetic ${kind} ${nodes}`,
				source: generateSyntheticDsl({ seed: 42, nodes, kind }),
			})),
		),
	];
}

interface Row {
	name: string;
	nodes: number;
	edges: number;
	dge: { ms: number; metrics: LayoutMetrics };
	elk: { ms: number; metrics: LayoutMetrics };
}

function hardTotal(metrics: LayoutMetrics): number {
	return LAYOUT_METRIC_HARD_KEYS.reduce(
		(sum, key) => sum + (key === "groupOverlapAreaRatio" ? 0 : metrics[key]),
		0,
	);
}

function hardDetail(metrics: LayoutMetrics): string {
	const parts = LAYOUT_METRIC_HARD_KEYS.filter(
		(key) => key !== "groupOverlapAreaRatio" && metrics[key] > 0,
	).map((key) => `${key} ${metrics[key]}`);
	return parts.length === 0
		? "0"
		: `${hardTotal(metrics)} (${parts.join(", ")})`;
}

function report(rows: readonly Row[]): string {
	const area = (m: LayoutMetrics) => Math.round((m.width * m.height) / 1000);
	const lines = [
		"# DGE vs ELK layered",
		"",
		"Generated by `DGE_ELK=1 npx vitest run test/benchmark/elk-comparison.test.ts`.",
		"",
		"Both engines get identical input: DGE measures and fits every label first, then ELK (elkjs, `layered`, orthogonal routing, `INCLUDE_CHILDREN`, DGE's spacing) lays out the same node sizes, group/lane hierarchy with the same paddings, and the same edge-label sizes. Both results are scored with `measureLayoutQuality`. DGE time is the whole `renderDiagramDsl` call (parse, text measurement, layout, routing, labels, export); ELK time is `elk.layout` alone. ELK has no notion of ports, abutting equal-thickness lanes or explicit constraints, so lanes become ordinary compound nodes there, and fixtures arranged with `relative-position` constraints (microservice, fan-out; laid out by Dagre plus those constraints in DGE) are not like for like.",
		"",
		"Hard = node overlaps + group overlaps + foreign nodes in groups + label overflows + edges through nodes + edge-label collisions + shared endpoints (target 0).",
		"",
		"| Diagram | Nodes | Edges | Hard DGE | Hard ELK | Crossings DGE / ELK | Bends/edge DGE / ELK | Area k px² DGE / ELK | Aspect DGE / ELK | ms DGE / ELK |",
		"| --- | ---: | ---: | --- | --- | ---: | ---: | ---: | ---: | ---: |",
		...rows.map((row) => {
			const d = row.dge.metrics;
			const e = row.elk.metrics;
			return `| ${row.name} | ${row.nodes} | ${row.edges} | ${hardDetail(d)} | ${hardDetail(e)} | ${d.crossings} / ${e.crossings} | ${d.bendsPerEdge.toFixed(2)} / ${e.bendsPerEdge.toFixed(2)} | ${area(d)} / ${area(e)} | ${d.aspectRatio.toFixed(2)} / ${e.aspectRatio.toFixed(2)} | ${Math.round(row.dge.ms)} / ${Math.round(row.elk.ms)} |`;
		}),
		"",
	];
	const sum = (pick: (row: Row) => number) =>
		rows.reduce((total, row) => total + pick(row), 0);
	lines.push(
		"## Totals",
		"",
		"| | DGE | ELK |",
		"| --- | ---: | ---: |",
		`| Diagrams with hard violations | ${rows.filter((row) => hardTotal(row.dge.metrics) > 0).length} | ${rows.filter((row) => hardTotal(row.elk.metrics) > 0).length} |`,
		`| Hard violations | ${sum((row) => hardTotal(row.dge.metrics))} | ${sum((row) => hardTotal(row.elk.metrics))} |`,
		`| Crossings | ${sum((row) => row.dge.metrics.crossings)} | ${sum((row) => row.elk.metrics.crossings)} |`,
		`| Bends | ${sum((row) => row.dge.metrics.bends)} | ${sum((row) => row.elk.metrics.bends)} |`,
		`| Time (ms) | ${Math.round(sum((row) => row.dge.ms))} | ${Math.round(sum((row) => row.elk.ms))} |`,
		"",
	);
	return lines.join("\n");
}

async function compare(item: Case): Promise<Row> {
	const started = performance.now();
	const result = renderDiagramDsl(item.source, {
		textMeasurer: new DeterministicTextMeasurer(),
	});
	const dgeMs = performance.now() - started;
	expect(result.diagram, item.name).toBeDefined();
	const diagram = result.diagram as CoordinatedDiagram;
	const options = { containment: containmentRelations(result.constraints) };
	const elk = await layoutWithElk(diagram);
	return {
		name: item.name,
		nodes: diagram.nodes.length,
		edges: diagram.edges.length,
		dge: { ms: dgeMs, metrics: measureLayoutQuality(diagram, options) },
		elk: {
			ms: elk.layoutMs,
			metrics: measureLayoutQuality(elk.diagram, options),
		},
	};
}

describe("ELK adapter", () => {
	it("lays out the same nodes, groups and edges", async () => {
		const source = readFileSync(
			new URL("examples/groups.yaml", REPO_ROOT),
			"utf8",
		);
		const result = renderDiagramDsl(source, {
			textMeasurer: new DeterministicTextMeasurer(),
		});
		const diagram = result.diagram as CoordinatedDiagram;
		const elk = (await layoutWithElk(diagram)).diagram;
		expect(elk.nodes.map((node) => node.id)).toEqual(
			diagram.nodes.map((node) => node.id),
		);
		for (const [index, node] of elk.nodes.entries()) {
			const before = diagram.nodes[index];
			expect(node.box.width).toBe(before?.box.width);
			expect(node.box.height).toBe(before?.box.height);
		}
		// Every group still holds its members.
		for (const group of elk.groups) {
			for (const id of group.nodeIds) {
				const box = elk.nodes.find((node) => node.id === id)?.box;
				expect(box).toBeDefined();
				if (box === undefined) continue;
				expect(box.x).toBeGreaterThanOrEqual(group.box.x - 0.5);
				expect(box.x + box.width).toBeLessThanOrEqual(
					group.box.x + group.box.width + 0.5,
				);
			}
		}
		for (const edge of elk.edges) expect(edge.points.length).toBeGreaterThan(1);
	});
});

describe.skipIf(!enabled)("DGE vs ELK", () => {
	it("writes the comparison report", { timeout: 900_000 }, async () => {
		const rows: Row[] = [];
		for (const item of cases()) {
			const row = await compare(item);
			rows.push(row);
			console.log(
				`${row.name.padEnd(34)} hard ${hardTotal(row.dge.metrics)}/${hardTotal(row.elk.metrics)} crossings ${row.dge.metrics.crossings}/${row.elk.metrics.crossings} ms ${Math.round(row.dge.ms)}/${Math.round(row.elk.ms)}`,
			);
		}
		writeFileSync(REPORT_URL, report(rows));
	});
});
