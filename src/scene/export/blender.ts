import type { SolvedScene } from "../ir.js";
import { sceneToDocument } from "./json.js";

/**
 * A Blender Python script that builds the solved scene.
 *
 * Every object is a box mesh with its origin at the bottom center, so the
 * Blender object's location is exactly the scene `position` and its z
 * rotation the `yaw` (Blender is z-up and counter-clockwise like the
 * scene frame). A flat triangle on top marks the front. An object with an
 * `asset` whose name is a collection in the open file is placed as an
 * instance of that collection instead (its origin should be the bottom
 * center and its front the declared `front`).
 *
 * Everything goes into one collection named after the scene, which is
 * rebuilt when the script runs again. Run it in Blender's text editor, or
 * headless: `blender -b --python scene.py -- --render scene.png`.
 */
export function sceneToBlenderScript(scene: SolvedScene): string {
	const data = JSON.stringify(JSON.stringify(sceneToDocument(scene)));
	return `${HEADER}
DATA = json.loads(${data})
${BODY}`;
}

const HEADER = `# Generated by auto-graph from a dge-scene v1 document.
# Frame: x east, y north, z up, meters; origin at the room's south-west
# floor corner. Run in Blender, or headless:
#   blender -b --python this.py -- --render out.png
import json
import math
import sys

import bpy
`;

const BODY = `
LEVEL_COLORS = [
    (0.36, 0.55, 0.90, 1.0),
    (0.98, 0.76, 0.22, 1.0),
    (0.93, 0.45, 0.66, 1.0),
    (0.52, 0.80, 0.30, 1.0),
]
FRONT_ANGLE = {"+x": 0.0, "+y": 90.0, "-x": 180.0, "-y": -90.0}


def material(name, color):
    mat = bpy.data.materials.get(name) or bpy.data.materials.new(name)
    mat.diffuse_color = color
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    if bsdf is not None:
        bsdf.inputs["Base Color"].default_value = color
    return mat


def box_mesh(name, width, depth, height):
    hx, hy = width / 2, depth / 2
    verts = [
        (-hx, -hy, 0), (hx, -hy, 0), (hx, hy, 0), (-hx, hy, 0),
        (-hx, -hy, height), (hx, -hy, height), (hx, hy, height), (-hx, hy, height),
    ]
    faces = [(0, 3, 2, 1), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7)]
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(verts, [], faces)
    mesh.update()
    return mesh


def front_marker(name, width, depth, height, front):
    # A flat triangle on the top face, pointing out of the front side.
    angle = math.radians(FRONT_ANGLE[front])
    fx, fy = math.cos(angle), math.sin(angle)
    reach = abs(fx) * width / 2 + abs(fy) * depth / 2
    size = max(0.04, min(width, depth) * 0.25)
    tip = (fx * reach, fy * reach)
    side = (-fy * size * 0.6, fx * size * 0.6)
    back = (fx * (reach - size), fy * (reach - size))
    z = height + 0.002
    verts = [
        (tip[0], tip[1], z),
        (back[0] + side[0], back[1] + side[1], z),
        (back[0] - side[0], back[1] - side[1], z),
    ]
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(verts, [], [(0, 1, 2)])
    mesh.update()
    return mesh


def level_of(obj, by_id):
    level, seen, at = 0, set(), obj.get("supportedBy")
    while at is not None and at not in seen:
        seen.add(at)
        level += 1
        at = by_id[at].get("supportedBy")
    return level


def build(data):
    name = "DGE " + data["name"]
    old = bpy.data.collections.get(name)
    if old is not None:
        for item in list(old.all_objects):
            bpy.data.objects.remove(item, do_unlink=True)
        bpy.data.collections.remove(old)
    collection = bpy.data.collections.new(name)
    bpy.context.scene.collection.children.link(collection)

    width = data["bounds"]["width"]
    depth = data["bounds"]["depth"]
    # A 5 cm slab whose top is the floor (z = 0).
    floor = bpy.data.objects.new("floor", box_mesh("floor", width, depth, 0.05))
    floor.location = (width / 2, depth / 2, -0.05)
    floor.data.materials.append(material("dge.floor", (0.82, 0.80, 0.76, 1.0)))
    collection.objects.link(floor)

    marker_mat = material("dge.front", (0.12, 0.23, 0.54, 1.0))
    by_id = {item["id"]: item for item in data["objects"]}
    for item in data["objects"]:
        w, d, h = item["size"]
        x, y, z = item["position"]
        asset = item.get("asset")
        source = bpy.data.collections.get(asset) if asset else None
        if source is not None:
            obj = bpy.data.objects.new(item["id"], None)
            obj.instance_type = "COLLECTION"
            obj.instance_collection = source
        else:
            obj = bpy.data.objects.new(item["id"], box_mesh(item["id"], w, d, h))
            color = LEVEL_COLORS[level_of(item, by_id) % len(LEVEL_COLORS)]
            obj.data.materials.append(material("dge.level." + str(level_of(item, by_id)), color))
            obj.color = color
        obj.location = (x, y, z)
        obj.rotation_euler = (0.0, 0.0, math.radians(item["yaw"]))
        obj["dge_id"] = item["id"]
        obj["dge_front"] = item["front"]
        if item.get("supportedBy"):
            obj["dge_supported_by"] = item["supportedBy"]
        if asset:
            obj["dge_asset"] = asset
        collection.objects.link(obj)

        marker = bpy.data.objects.new(item["id"] + ".front", front_marker(item["id"] + ".front", w, d, h, item["front"]))
        marker.data.materials.append(marker_mat)
        marker.color = marker_mat.diffuse_color
        marker.parent = obj
        collection.objects.link(marker)

        label = bpy.data.curves.new(item["id"] + ".label", "FONT")
        label.body = item.get("label") or item["id"]
        label.size = max(0.08, min(0.18, min(w, d) * 0.3))
        label.align_x = "CENTER"
        label.align_y = "CENTER"
        text = bpy.data.objects.new(item["id"] + ".label", label)
        text.location = (x, y, z + h + 0.01)
        text.data.materials.append(material("dge.label", (0.03, 0.03, 0.08, 1.0)))
        collection.objects.link(text)

    # An orthographic camera from the south-west, above, and a sun.
    span = max(width, depth)
    target = bpy.data.objects.new("dge.target", None)
    target.location = (width / 2, depth / 2, 0.0)
    collection.objects.link(target)
    camera = bpy.data.objects.new("dge.camera", bpy.data.cameras.new("dge.camera"))
    camera.data.type = "ORTHO"
    camera.data.ortho_scale = span * 1.5
    camera.location = (width / 2 - span, depth / 2 - span * 1.2, span * 1.3)
    track = camera.constraints.new("TRACK_TO")
    track.target = target
    track.track_axis = "TRACK_NEGATIVE_Z"
    track.up_axis = "UP_Y"
    collection.objects.link(camera)
    sun = bpy.data.objects.new("dge.sun", bpy.data.lights.new("dge.sun", "SUN"))
    sun.data.energy = 3.0
    sun.rotation_euler = (math.radians(40), 0.0, math.radians(-30))
    collection.objects.link(sun)
    bpy.context.scene.camera = camera
    return collection


def render(path):
    # Cycles on the CPU: needs no GPU or display, so it also runs headless.
    scene = bpy.context.scene
    scene.render.engine = "CYCLES"
    scene.cycles.device = "CPU"
    scene.cycles.samples = 24
    scene.cycles.use_denoising = False
    scene.render.resolution_x = 1200
    scene.render.resolution_y = 900
    world = scene.world or bpy.data.worlds.new("dge.world")
    scene.world = world
    world.use_nodes = True
    background = world.node_tree.nodes.get("Background")
    if background is not None:
        background.inputs["Color"].default_value = (0.9, 0.92, 0.95, 1.0)
        background.inputs["Strength"].default_value = 0.6
    scene.render.filepath = path
    bpy.ops.render.render(write_still=True)


COLLECTION = build(DATA)
ARGS = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
if "--render" in ARGS:
    # Render only this scene, not whatever else the file holds.
    for other in bpy.context.scene.objects:
        if other.name not in COLLECTION.all_objects:
            other.hide_render = True
    render(ARGS[ARGS.index("--render") + 1])
`;
