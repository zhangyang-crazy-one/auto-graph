import type { SolvedScene } from "../ir.js";
import { positionAfter, sampleElapsed, timePath } from "../path-timing.js";
import { sceneToDocument } from "./json.js";

/** Seconds between the keyframes of an agent walking its path. */
const TRACK_STEP = 0.1;

/**
 * A Blender Python script that builds the solved scene.
 *
 * Every object is a box mesh with its origin at the bottom center, so the
 * Blender object's location is exactly the scene `position` and its z
 * rotation the `yaw` (Blender is z-up and counter-clockwise like the
 * scene frame). A flat triangle on top marks the front. An object with an
 * `asset` whose name is a collection in the open file is placed as an
 * instance of that collection instead (its origin should be the bottom
 * center and its front the declared `front`).
 *
 * Openings are strips across the wall line. Each path is a curve a hair
 * above the floor, and its agent a cylinder that walks it: keyframes every
 * 0.1 s and at every corner, at 24 frames a second, so the cylinder is at
 * each corner exactly at the time the JSON gives.
 *
 * Everything goes into one collection named after the scene, which is
 * rebuilt when the script runs again. Run it in Blender's text editor, or
 * headless: `blender -b --python scene.py -- --render scene.png`.
 */
export function sceneToBlenderScript(scene: SolvedScene): string {
	const data = JSON.stringify(JSON.stringify(sceneToDocument(scene)));
	const tracks = JSON.stringify(JSON.stringify(agentTracks(scene)));
	return `${HEADER}
DATA = json.loads(${data})
# Where each path's agent is over time: [seconds, x, y].
TRACKS = json.loads(${tracks})
${BODY}`;
}

/** Each path's agent sampled over time, for keyframes. */
function agentTracks(scene: SolvedScene): Record<string, number[][]> {
	const tracks: Record<string, number[][]> = {};
	for (const path of scene.paths) {
		const agent = scene.agents.find((item) => item.id === path.agent);
		if (agent === undefined) continue;
		const corners = path.points.map(([x, y]) => ({ x, y }));
		const timing = timePath(corners, agent.speed, agent.accel, path.start);
		// Sampled on time since setting off and rounded only when written,
		// so the first key is the start and the last the end.
		tracks[path.id] = sampleElapsed(timing, TRACK_STEP).map((since) => {
			const at = positionAfter(corners, timing, since);
			return [round(path.start + since), round(at.x), round(at.y)];
		});
	}
	return tracks;
}

function round(value: number): number {
	const rounded = Math.round(value * 1e4) / 1e4;
	return Object.is(rounded, -0) ? 0 : rounded;
}

const HEADER = `# Generated by auto-graph from a dge-scene v1 document.
# Frame: x east, y north, z up, meters; origin at the room's south-west
# floor corner. Run in Blender, or headless:
#   blender -b --python this.py -- --render out.png [--size 1200x900] [--samples 24] [--frame N]
#   (frame 0 is when the first agent sets off; 24 frames a second)
#   blender -b --python this.py -- --animation out.mp4   (the agents walking their paths)
import json
import math
import sys

import bpy
`;

const BODY = `
LEVEL_COLORS = [
    (0.36, 0.55, 0.90, 1.0),
    (0.98, 0.76, 0.22, 1.0),
    (0.93, 0.45, 0.66, 1.0),
    (0.52, 0.80, 0.30, 1.0),
]
FRONT_ANGLE = {"+x": 0.0, "+y": 90.0, "-x": 180.0, "-y": -90.0}
# The top view's path colors, in the same order.
PATH_COLORS = [
    (0.05, 0.58, 0.53, 1.0),
    (0.76, 0.25, 0.05, 1.0),
    (0.49, 0.23, 0.93, 1.0),
    (0.01, 0.41, 0.63, 1.0),
    (0.75, 0.07, 0.24, 1.0),
]
FPS = 24
# Blender's last frame is 1,048,574; stay well inside it.
MAX_FRAMES = 1_000_000


def material(name, color):
    mat = bpy.data.materials.get(name) or bpy.data.materials.new(name)
    mat.diffuse_color = color
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    if bsdf is not None:
        bsdf.inputs["Base Color"].default_value = color
    return mat


def box_mesh(name, width, depth, height):
    hx, hy = width / 2, depth / 2
    verts = [
        (-hx, -hy, 0), (hx, -hy, 0), (hx, hy, 0), (-hx, hy, 0),
        (-hx, -hy, height), (hx, -hy, height), (hx, hy, height), (-hx, hy, height),
    ]
    faces = [(0, 3, 2, 1), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7)]
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(verts, [], faces)
    mesh.update()
    return mesh


def front_marker(name, width, depth, height, front):
    # A flat triangle on the top face, pointing out of the front side.
    angle = math.radians(FRONT_ANGLE[front])
    fx, fy = math.cos(angle), math.sin(angle)
    reach = abs(fx) * width / 2 + abs(fy) * depth / 2
    size = max(0.04, min(width, depth) * 0.25)
    tip = (fx * reach, fy * reach)
    side = (-fy * size * 0.6, fx * size * 0.6)
    back = (fx * (reach - size), fy * (reach - size))
    z = height + 0.002
    verts = [
        (tip[0], tip[1], z),
        (back[0] + side[0], back[1] + side[1], z),
        (back[0] - side[0], back[1] - side[1], z),
    ]
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(verts, [], [(0, 1, 2)])
    mesh.update()
    return mesh


def cylinder_mesh(name, radius, height, sides=24):
    # Origin at the bottom center, like the boxes.
    ring = [(radius * math.cos(2 * math.pi * k / sides), radius * math.sin(2 * math.pi * k / sides)) for k in range(sides)]
    verts = [(x, y, 0.0) for x, y in ring] + [(x, y, height) for x, y in ring]
    faces = [tuple(range(sides - 1, -1, -1)), tuple(range(sides, 2 * sides))]
    faces += [(k, (k + 1) % sides, sides + (k + 1) % sides, sides + k) for k in range(sides)]
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(verts, [], faces)
    mesh.update()
    return mesh


def add_openings(data, collection):
    width = data["bounds"]["width"]
    depth = data["bounds"]["depth"]
    mat = material("dge.opening", (0.05, 0.58, 0.53, 1.0))
    for opening in data.get("openings", []):
        wall, at, span = opening["wall"], opening["at"], opening["width"]
        if wall in ("south", "north"):
            center = (at, 0.0 if wall == "south" else depth)
            size = (span, 0.12)
        else:
            center = (0.0 if wall == "west" else width, at)
            size = (0.12, span)
        name = "opening." + opening["id"]
        obj = bpy.data.objects.new(name, box_mesh(name, size[0], size[1], 0.01))
        obj.location = (center[0], center[1], 0.0)
        obj.data.materials.append(mat)
        obj.color = mat.diffuse_color
        obj["dge_opening"] = opening["id"]
        obj["dge_wall"] = wall
        collection.objects.link(obj)


def add_paths(data, collection):
    agents = {agent["id"]: agent for agent in data.get("agents", [])}
    tracks = [track for track in TRACKS.values() if track]
    # The timeline starts when the first agent sets off; a walk too long
    # for Blender's frame range at 24 fps is slowed down (fps_base) so it
    # fits. Frame = (t - origin) * dge_fps.
    origin = min((track[0][0] for track in tracks), default=0.0)
    span = max((track[-1][0] for track in tracks), default=0.0) - origin
    base = max(1.0, span * FPS / MAX_FRAMES)
    rate = FPS / base
    # New keys interpolate linearly (set through the preferences, which
    # every Blender version has, not through per-key F-curve access).
    edit = bpy.context.preferences.edit
    interpolation = edit.keyframe_new_interpolation_type
    edit.keyframe_new_interpolation_type = "LINEAR"
    try:
        for k, path in enumerate(data.get("paths", [])):
            color = PATH_COLORS[k % len(PATH_COLORS)]
            mat = material("dge.path." + str(k % len(PATH_COLORS)), color)
            name = "path." + path["id"]
            curve = bpy.data.curves.new(name, "CURVE")
            curve.dimensions = "3D"
            curve.bevel_depth = 0.02
            spline = curve.splines.new("POLY")
            spline.points.add(len(path["points"]) - 1)
            for point, (x, y, z) in zip(spline.points, path["points"]):
                point.co = (x, y, z + 0.01, 1.0)
            line = bpy.data.objects.new(name, curve)
            line.data.materials.append(mat)
            line.color = color
            line["dge_path"] = path["id"]
            collection.objects.link(line)

            agent = agents.get(path["agent"])
            track = TRACKS.get(path["id"])
            if agent is None or not track:
                continue
            name = "agent." + path["id"]
            body = bpy.data.objects.new(name, cylinder_mesh(name, agent["radius"], agent["height"]))
            body.data.materials.append(mat)
            body.color = color
            body["dge_path"] = path["id"]
            body["dge_agent"] = agent["id"]
            collection.objects.link(body)
            for t, x, y in track:
                body.location = (x, y, 0.0)
                body.keyframe_insert("location", frame=(t - origin) * rate)
    finally:
        edit.keyframe_new_interpolation_type = interpolation
    if not tracks:
        return
    # Only a scene with walking agents sets the timeline.
    scene = bpy.context.scene
    scene.render.fps = FPS
    scene.render.fps_base = base
    scene.frame_start = 0
    scene.frame_end = max(1, math.ceil(span * rate))
    scene["dge_time_origin"] = origin
    scene["dge_fps"] = rate


def level_of(obj, by_id):
    level, seen, at = 0, set(), obj.get("supportedBy")
    while at is not None and at not in seen:
        seen.add(at)
        level += 1
        at = by_id[at].get("supportedBy")
    return level


def build(data):
    name = "DGE " + data["name"]
    old = bpy.data.collections.get(name)
    if old is not None:
        for item in list(old.all_objects):
            bpy.data.objects.remove(item, do_unlink=True)
        bpy.data.collections.remove(old)
    collection = bpy.data.collections.new(name)
    bpy.context.scene.collection.children.link(collection)

    width = data["bounds"]["width"]
    depth = data["bounds"]["depth"]
    # A 5 cm slab whose top is the floor (z = 0).
    floor = bpy.data.objects.new("floor", box_mesh("floor", width, depth, 0.05))
    floor.location = (width / 2, depth / 2, -0.05)
    floor.data.materials.append(material("dge.floor", (0.82, 0.80, 0.76, 1.0)))
    collection.objects.link(floor)

    marker_mat = material("dge.front", (0.12, 0.23, 0.54, 1.0))
    by_id = {item["id"]: item for item in data["objects"]}
    for item in data["objects"]:
        w, d, h = item["size"]
        x, y, z = item["position"]
        asset = item.get("asset")
        source = bpy.data.collections.get(asset) if asset else None
        if source is not None:
            obj = bpy.data.objects.new(item["id"], None)
            obj.instance_type = "COLLECTION"
            obj.instance_collection = source
        else:
            obj = bpy.data.objects.new(item["id"], box_mesh(item["id"], w, d, h))
            color = LEVEL_COLORS[level_of(item, by_id) % len(LEVEL_COLORS)]
            obj.data.materials.append(material("dge.level." + str(level_of(item, by_id)), color))
            obj.color = color
        obj.location = (x, y, z)
        obj.rotation_euler = (0.0, 0.0, math.radians(item["yaw"]))
        obj["dge_id"] = item["id"]
        obj["dge_front"] = item["front"]
        if item.get("supportedBy"):
            obj["dge_supported_by"] = item["supportedBy"]
        if asset:
            obj["dge_asset"] = asset
        collection.objects.link(obj)

        marker = bpy.data.objects.new(item["id"] + ".front", front_marker(item["id"] + ".front", w, d, h, item["front"]))
        marker.data.materials.append(marker_mat)
        marker.color = marker_mat.diffuse_color
        marker.parent = obj
        collection.objects.link(marker)

        label = bpy.data.curves.new(item["id"] + ".label", "FONT")
        label.body = item.get("label") or item["id"]
        label.size = max(0.08, min(0.18, min(w, d) * 0.3))
        label.align_x = "CENTER"
        label.align_y = "CENTER"
        text = bpy.data.objects.new(item["id"] + ".label", label)
        text.location = (x, y, z + h + 0.01)
        text.data.materials.append(material("dge.label", (0.03, 0.03, 0.08, 1.0)))
        collection.objects.link(text)

    add_openings(data, collection)
    add_paths(data, collection)

    # An orthographic camera from the south-west, above, and a sun.
    span = max(width, depth)
    target = bpy.data.objects.new("dge.target", None)
    # Aim a little above the floor so tall objects at the back stay in view.
    top = max([item["aabb"]["max"][2] for item in data["objects"]] + [0.0])
    target.location = (width / 2, depth / 2, top * 0.4)
    collection.objects.link(target)
    camera = bpy.data.objects.new("dge.camera", bpy.data.cameras.new("dge.camera"))
    camera.data.type = "ORTHO"
    camera.data.ortho_scale = span * 1.6
    camera.location = (width / 2 - span, depth / 2 - span * 1.2, span * 1.3)
    track = camera.constraints.new("TRACK_TO")
    track.target = target
    track.track_axis = "TRACK_NEGATIVE_Z"
    track.up_axis = "UP_Y"
    collection.objects.link(camera)
    sun = bpy.data.objects.new("dge.sun", bpy.data.lights.new("dge.sun", "SUN"))
    sun.data.energy = 3.0
    sun.rotation_euler = (math.radians(40), 0.0, math.radians(-30))
    collection.objects.link(sun)
    bpy.context.scene.camera = camera
    return collection


def render(path, width=1200, height=900, samples=24, animation=False):
    # Cycles on the CPU: needs no GPU or display, so it also runs headless.
    scene = bpy.context.scene
    scene.render.engine = "CYCLES"
    scene.cycles.device = "CPU"
    scene.cycles.samples = samples
    scene.cycles.use_denoising = True
    scene.cycles.seed = 0
    scene.render.resolution_x = width
    scene.render.resolution_y = height
    world = scene.world or bpy.data.worlds.new("dge.world")
    scene.world = world
    world.use_nodes = True
    background = world.node_tree.nodes.get("Background")
    if background is not None:
        background.inputs["Color"].default_value = (0.9, 0.92, 0.95, 1.0)
        background.inputs["Strength"].default_value = 0.6
    # No date, render time or file name in the image: the same scene
    # gives the same bytes.
    for name in dir(scene.render):
        if name.startswith("use_stamp"):
            setattr(scene.render, name, False)
    settings = scene.render.image_settings
    if animation:
        settings.file_format = "FFMPEG"
        scene.render.ffmpeg.format = "MPEG4"
        scene.render.ffmpeg.codec = "H264"
        scene.render.filepath = path
        bpy.ops.render.render(animation=True)
        return
    if path.lower().endswith((".jpg", ".jpeg")):
        settings.file_format = "JPEG"
        settings.quality = 88
    else:
        settings.file_format = "PNG"
        settings.compression = 100
    settings.color_mode = "RGB"
    scene.render.filepath = path
    bpy.ops.render.render(write_still=True)


COLLECTION = build(DATA)
ARGS = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
if "--frame" in ARGS:
    # A moment of the paths' animation, in frames (24 a second).
    bpy.context.scene.frame_set(int(ARGS[ARGS.index("--frame") + 1]))
if "--render" in ARGS or "--animation" in ARGS:
    # Render only this scene, not whatever else the file holds.
    for other in bpy.context.scene.objects:
        if other.name not in COLLECTION.all_objects:
            other.hide_render = True
    size = ARGS[ARGS.index("--size") + 1] if "--size" in ARGS else "1200x900"
    samples = int(ARGS[ARGS.index("--samples") + 1]) if "--samples" in ARGS else 24
    width, height = (int(part) for part in size.split("x"))
    if "--animation" in ARGS:
        render(ARGS[ARGS.index("--animation") + 1], width, height, samples, animation=True)
    else:
        render(ARGS[ARGS.index("--render") + 1], width, height, samples)
`;
