import type { PlacedSceneObject, SolvedScene } from "../ir.js";
import { type GridTerrain, sceneTerrain } from "../terrain/index.js";
import {
	box,
	COLORS,
	cylinder,
	frontMarker,
	LEVEL_COLORS,
	levelOf,
	PATH_COLORS,
	type Rgb,
	ribbon,
	type Solid,
	sceneMarks,
	terrainSolid,
} from "./shapes.js";
import { agentTracks, onGround, pathLines } from "./tracks.js";

export interface SceneUsdOptions {
	/**
	 * Where each object's asset is, with `{asset}` standing for its
	 * `asset` name, e.g. `./assets/{asset}.usd`. Objects with an asset
	 * then get a `geometry` variant set: `asset` (selected) references
	 * that file's default prim, `placeholder` keeps the box.
	 */
	assetPath?: string;
}

/**
 * The solved scene as a USD stage in text form (`.usda`), for Omniverse,
 * Blender, Houdini and other USD tools.
 *
 * The stage is z-up in metres (`upAxis = "Z"`, `metersPerUnit = 1`), the
 * scene frame itself, so no axis is converted: each object is an Xform
 * whose `xformOp:translate` is its `position` and `xformOp:orient` its
 * `quaternion` (written w first, as USD has it), holding a placeholder
 * box (origin at the bottom center) and a triangle on top at its front,
 * colored by stacking level with UsdPreviewSurface materials. Prim names
 * are the ids made into identifiers (other characters become `_`); the
 * ids themselves and the front, size, support, asset, group, label and
 * WGS84 position are `userProperties:dge_*` attributes, which Blender
 * imports as custom properties.
 *
 * With `assetPath`, an object that names an asset references it (see
 * {@link SceneUsdOptions}); the asset's origin should be its bottom center,
 * its front the declared `front`, and its units metres, z up.
 *
 * The floor (a 5 cm slab with its top at z = 0) or the terrain mesh,
 * openings, paths, lines and waypoints (linear BasisCurves, waypoints
 * also Points) and landmark pins come along. Each path's agent is a
 * cylinder whose translate is time-sampled along it: a sample every
 * 0.1 s and at every corner, 24 time codes a second, time code 0 when
 * the first agent sets off (`dge_time_origin` in the layer's
 * customLayerData gives that in scene seconds).
 */
export function sceneToUsda(
	scene: SolvedScene,
	options: SceneUsdOptions = {},
): string {
	const ground = sceneTerrain(scene);
	const root = `/${identifier(scene.name, "Scene")}`;
	const out = new Usda();
	const tracks = agentTracks(scene, ground);
	const keyed = scene.paths.filter(
		(path) => (tracks[path.id]?.length ?? 0) > 0,
	);
	const timeOrigin =
		keyed.length === 0
			? undefined
			: Math.min(...keyed.map((path) => tracks[path.id]?.[0]?.[0] ?? 0));
	const endTime =
		timeOrigin === undefined
			? 0
			: Math.max(...keyed.map((path) => tracks[path.id]?.at(-1)?.[0] ?? 0)) -
				timeOrigin;

	out.line("#usda 1.0");
	out.open("(");
	out.line(`defaultPrim = ${text(root.slice(1))}`);
	out.line(`doc = "Generated by auto-graph from a dge-scene v1 document."`);
	out.line("metersPerUnit = 1");
	out.line('upAxis = "Z"');
	if (timeOrigin !== undefined) {
		out.line("timeCodesPerSecond = 24");
		out.line("framesPerSecond = 24");
		out.line("startTimeCode = 0");
		out.line(`endTimeCode = ${num(Math.ceil(endTime * 24))}`);
	}
	out.open("customLayerData = {");
	out.line('string dge_format = "dge-scene"');
	out.line("int dge_version = 1");
	out.line(`bool dge_valid = ${scene.valid ? 1 : 0}`);
	if (scene.geo !== undefined) {
		const { origin } = scene.geo;
		out.line(
			`double3 dge_geo_origin = ${tuple([origin.lat, origin.lon, origin.alt])}`,
		);
		out.line(`double dge_geo_heading = ${num(scene.geo.heading)}`);
	}
	if (timeOrigin !== undefined) {
		out.line(`double dge_time_origin = ${num(timeOrigin)}`);
	}
	out.close("}");
	out.close(")");
	out.line("");

	out.open(`def Xform ${text(root.slice(1))}`, "{");
	out.line(`custom string userProperties:dge_scene = ${text(scene.name)}`);
	const looks = materials(out, root);

	const { width, depth } = scene.bounds;
	const marks = sceneMarks(scene);
	if (ground === undefined) {
		out.open('def Xform "floor"', "{");
		translateOnly(out, [width / 2, depth / 2, -0.05]);
		mesh(out, "slab", box(width, depth, 0.05), looks("floor"));
		out.close("}");
	} else {
		terrain(out, ground, looks("ground"));
	}

	const byId = new Map(scene.objects.map((item) => [item.id, item]));
	const names = new Names();
	out.open('def Xform "objects"', "{");
	for (const item of scene.objects) {
		object(out, item, names.take(item.id), byId, looks, options.assetPath);
	}
	out.close("}");

	if (scene.openings.length > 0) {
		const names = new Names();
		out.open('def Xform "openings"', "{");
		for (const opening of scene.openings) {
			const along = opening.wall === "south" || opening.wall === "north";
			const center: [number, number, number] = along
				? [opening.at, opening.wall === "south" ? 0 : depth, 0]
				: [opening.wall === "west" ? 0 : width, opening.at, 0];
			const size = along ? [opening.width, 0.12] : [0.12, opening.width];
			out.open(`def Xform ${text(names.take(opening.id))}`, "{");
			properties(out, { dge_opening: opening.id, dge_wall: opening.wall });
			translateOnly(out, center);
			mesh(
				out,
				"strip",
				box(size[0] as number, size[1] as number, 0.01),
				looks("opening"),
			);
			out.close("}");
		}
		out.close("}");
	}

	const lines = pathLines(scene, ground);
	if (scene.paths.length > 0) {
		const names = new Names();
		out.open('def Xform "paths"', "{");
		scene.paths.forEach((path, k) => {
			const color = `path.${k % PATH_COLORS.length}`;
			curve(
				out,
				names.take(path.id),
				lines[path.id] ?? [],
				(marks.paths[path.id] ?? 0.02) * 2,
				looks(color),
				{
					dge_path: path.id,
				},
			);
		});
		out.close("}");
	}

	if (timeOrigin !== undefined) {
		const names = new Names();
		out.open('def Xform "agents"', "{");
		for (const path of keyed) {
			const agent = scene.agents.find((item) => item.id === path.agent);
			if (agent === undefined) continue;
			const k = scene.paths.indexOf(path);
			out.open(`def Xform ${text(names.take(path.id))}`, "{");
			properties(out, { dge_path: path.id, dge_agent: agent.id });
			const samples = (tracks[path.id] as number[][]).map(
				([t, x, y, z]) =>
					`${num(((t as number) - timeOrigin) * 24)}: ${tuple([x as number, y as number, z as number])}`,
			);
			out.open("double3 xformOp:translate.timeSamples = {");
			for (const sample of samples) out.line(`${sample},`);
			out.close("}");
			out.line('uniform token[] xformOpOrder = ["xformOp:translate"]');
			mesh(
				out,
				"body",
				cylinder(agent.radius, agent.height, 24),
				looks(`path.${k % PATH_COLORS.length}`),
			);
			out.close("}");
		}
		out.close("}");
	}

	if ((scene.landmarks ?? []).length > 0) {
		const names = new Names();
		const { radius, height } = marks.pin;
		out.open('def Xform "landmarks"', "{");
		for (const landmark of scene.landmarks ?? []) {
			const [x, y] = landmark.position;
			const z = ground === undefined ? 0 : ground.heightNear(x, y);
			out.open(`def Xform ${text(names.take(landmark.id))}`, "{");
			properties(out, {
				dge_landmark: landmark.id,
				dge_geo: [landmark.geo.lat, landmark.geo.lon, landmark.geo.alt],
			});
			translateOnly(out, [x, y, z]);
			mesh(out, "pin", cylinder(radius, height, 12), looks("landmark"));
			out.close("}");
		}
		out.close("}");
	}

	if ((scene.lines ?? []).length > 0) {
		const names = new Names();
		out.open('def Xform "lines"', "{");
		for (const line of scene.lines ?? []) {
			if (line.width !== undefined) {
				// A road: its surface on the ground.
				out.open(`def Xform ${text(names.take(line.id))}`, "{");
				properties(out, { dge_line: line.id, dge_width: line.width });
				mesh(
					out,
					"surface",
					ribbon(onGround(line.points, ground), line.width, ground),
					looks("line"),
				);
				out.close("}");
				continue;
			}
			curve(
				out,
				names.take(line.id),
				onGround(line.points, ground),
				marks.line * 2,
				looks("line"),
				{
					dge_line: line.id,
				},
			);
		}
		out.close("}");
	}

	if ((scene.waypoints ?? []).length > 0) {
		const names = new Names();
		const radius = marks.waypoint;
		out.open('def Xform "waypoints"', "{");
		for (const item of scene.waypoints ?? []) {
			const name = names.take(item.id);
			curve(
				out,
				name,
				item.points,
				(radius / 3) * 2,
				looks("waypoint"),
				{
					dge_waypoints: item.id,
					dge_height: item.height,
				},
				radius * 2,
			);
		}
		out.close("}");
	}

	out.close("}");
	return out.toString();
}

function object(
	out: Usda,
	item: PlacedSceneObject,
	name: string,
	byId: ReadonlyMap<string, PlacedSceneObject>,
	looks: (name: string) => string,
	assetPath: string | undefined,
): void {
	const level = levelOf(item, byId) % LEVEL_COLORS.length;
	const [w, d, h] = item.size;
	const asset =
		item.asset !== undefined && assetPath !== undefined
			? assetPath.replaceAll("{asset}", item.asset)
			: undefined;
	if (asset === undefined) {
		out.open(`def Xform ${text(name)}`, "{");
	} else {
		out.open(`def Xform ${text(name)} (`);
		out.line('variants = { string geometry = "asset" }');
		out.line('prepend variantSets = "geometry"');
		out.close(")");
		out.open("{");
	}
	const extras: Record<string, Value> = {
		dge_id: item.id,
		dge_front: item.front,
		dge_size: item.size,
	};
	if (item.supportedBy !== undefined)
		extras.dge_supported_by = item.supportedBy;
	if (item.asset !== undefined) extras.dge_asset = item.asset;
	if (item.group !== undefined) extras.dge_group = item.group;
	if (item.label !== undefined) extras.dge_label = item.label;
	if (item.geo !== undefined) {
		extras.dge_geo = [item.geo.lat, item.geo.lon, item.geo.alt];
	}
	properties(out, extras);
	const [qx, qy, qz, qw] = item.quaternion;
	const norm = Math.hypot(qx, qy, qz, qw);
	out.line(`double3 xformOp:translate = ${tuple(item.position)}`);
	out.line(
		`quatd xformOp:orient = ${tuple([qw / norm, qx / norm, qy / norm, qz / norm])}`,
	);
	out.line(
		'uniform token[] xformOpOrder = ["xformOp:translate", "xformOp:orient"]',
	);
	const placeholder = () => {
		mesh(out, "box", box(w, d, h), looks(`level.${level}`));
		mesh(out, "front", frontMarker(w, d, h, item.front), looks("front"));
	};
	if (asset === undefined) {
		placeholder();
	} else {
		out.open('variantSet "geometry" = {');
		out.open('"asset" {');
		out.open(`def "asset" (`);
		out.line(`prepend references = ${assetRef(asset)}`);
		out.close(")");
		out.open("{");
		out.close("}");
		out.close("}");
		out.open('"placeholder" {');
		placeholder();
		out.close("}");
		out.close("}");
	}
	out.close("}");
}

/** The ground mesh, under an Xform at the south-west sample. */
function terrain(out: Usda, ground: GridTerrain, material: string): void {
	const { solid, subdivision } = terrainSolid(ground);
	out.open('def Xform "terrain"', "{");
	properties(out, { dge_terrain_subdivision: subdivision });
	translateOnly(out, [ground.grid.origin.x, ground.grid.origin.y, 0]);
	mesh(out, "ground", solid, material);
	out.close("}");
}

/**
 * A linear curve through `points` under an Xform at the first point (so
 * the float points stay small on a large site); with `markers`, also a
 * point of that width at each vertex.
 */
function curve(
	out: Usda,
	name: string,
	points: readonly (readonly number[])[],
	width: number,
	material: string,
	extras: Record<string, Value>,
	markers?: number,
): void {
	if (points.length < 2) return;
	const [ox, oy, oz] = points[0] as [number, number, number];
	const local = points.map(
		([x, y, z]) =>
			[(x as number) - ox, (y as number) - oy, (z as number) - oz] as [
				number,
				number,
				number,
			],
	);
	out.open(`def Xform ${text(name)}`, "{");
	properties(out, extras);
	translateOnly(out, [ox, oy, oz]);
	out.open('def BasisCurves "curve" (', "");
	out.line('prepend apiSchemas = ["MaterialBindingAPI"]');
	out.close(")");
	out.open("{");
	out.line('uniform token type = "linear"');
	out.line(`int[] curveVertexCounts = [${local.length}]`);
	out.line(`point3f[] points = ${tuples(local)}`);
	out.line(`float3[] extent = ${tuples(bounds(local.flat()))}`);
	out.line(`float[] widths = [${num(width)}] (`);
	out.line('    interpolation = "constant"');
	out.line(")");
	out.line(`rel material:binding = <${material}>`);
	out.close("}");
	if (markers !== undefined) {
		out.open('def Points "markers" (');
		out.line('prepend apiSchemas = ["MaterialBindingAPI"]');
		out.close(")");
		out.open("{");
		out.line(`point3f[] points = ${tuples(local)}`);
		const half = markers / 2;
		const [lo, hi] = bounds(local.flat());
		out.line(
			`float3[] extent = ${tuples([
				[lo[0] - half, lo[1] - half, lo[2] - half],
				[hi[0] + half, hi[1] + half, hi[2] + half],
			])}`,
		);
		out.line(`float[] widths = [${num(markers)}] (`);
		out.line('    interpolation = "constant"');
		out.line(")");
		out.line(`rel material:binding = <${material}>`);
		out.close("}");
	}
	out.close("}");
}

/** A triangle mesh, faceted, bound to `material`. */
function mesh(out: Usda, name: string, solid: Solid, material: string): void {
	const points: [number, number, number][] = [];
	const normals: [number, number, number][] = [];
	for (let k = 0; k < solid.positions.length; k += 3) {
		points.push(solid.positions.slice(k, k + 3) as [number, number, number]);
		normals.push(solid.normals.slice(k, k + 3) as [number, number, number]);
	}
	out.open(`def Mesh ${text(name)} (`);
	out.line('prepend apiSchemas = ["MaterialBindingAPI"]');
	out.close(")");
	out.open("{");
	out.line(
		`int[] faceVertexCounts = [${new Array(solid.indices.length / 3).fill(3).join(", ")}]`,
	);
	out.line(`int[] faceVertexIndices = [${solid.indices.join(", ")}]`);
	out.line(`point3f[] points = ${tuples(points)}`);
	out.line(`normal3f[] normals = ${tuples(normals)} (`);
	out.line('    interpolation = "vertex"');
	out.line(")");
	out.line(`float3[] extent = ${tuples(bounds(solid.positions))}`);
	out.line('uniform token subdivisionScheme = "none"');
	out.line(`rel material:binding = <${material}>`);
	out.close("}");
}

/** One UsdPreviewSurface material per color; returns name → prim path. */
function materials(out: Usda, root: string): (name: string) => string {
	const all: [string, Rgb][] = [
		...LEVEL_COLORS.map((color, k): [string, Rgb] => [`level.${k}`, color]),
		...PATH_COLORS.map((color, k): [string, Rgb] => [`path.${k}`, color]),
		...Object.entries(COLORS).map(([name, color]): [string, Rgb] => [
			name,
			color as Rgb,
		]),
	];
	out.open('def Scope "Looks"', "{");
	for (const [name, color] of all) {
		const prim = name.replace(".", "_");
		const path = `${root}/Looks/${prim}`;
		out.open(`def Material ${text(prim)}`, "{");
		out.line(
			`token outputs:surface.connect = <${path}/Surface.outputs:surface>`,
		);
		out.open('def Shader "Surface"', "{");
		out.line('uniform token info:id = "UsdPreviewSurface"');
		out.line(`color3f inputs:diffuseColor = ${tuple(color)}`);
		out.line("float inputs:metallic = 0");
		out.line("float inputs:roughness = 0.8");
		out.line("token outputs:surface");
		out.close("}");
		out.close("}");
	}
	out.close("}");
	return (name) => `${root}/Looks/${name.replace(".", "_")}`;
}

function translateOnly(out: Usda, at: readonly number[]): void {
	out.line(`double3 xformOp:translate = ${tuple(at)}`);
	out.line('uniform token[] xformOpOrder = ["xformOp:translate"]');
}

type Value = string | number | readonly number[];

/** `userProperties:` attributes (Blender imports them as custom properties). */
function properties(out: Usda, values: Record<string, Value>): void {
	for (const [key, value] of Object.entries(values)) {
		if (typeof value === "string") {
			out.line(`custom string userProperties:${key} = ${text(value)}`);
		} else if (typeof value === "number") {
			const type = Number.isInteger(value) ? "int" : "double";
			out.line(`custom ${type} userProperties:${key} = ${num(value)}`);
		} else {
			out.line(`custom double3 userProperties:${key} = ${tuple(value)}`);
		}
	}
}

/** Per-axis min and max of xyz triples, as float3 extent corners. */
type Vec3 = [number, number, number];

function bounds(values: readonly number[]): [Vec3, Vec3] {
	const lo: Vec3 = [Infinity, Infinity, Infinity];
	const hi: Vec3 = [-Infinity, -Infinity, -Infinity];
	for (let k = 0; k < values.length; k += 1) {
		const c = k % 3;
		const value = values[k] as number;
		if (value < (lo[c] as number)) lo[c] = value;
		if (value > (hi[c] as number)) hi[c] = value;
	}
	return [lo, hi];
}

/** Prim names: ids made into identifiers, unique among their siblings. */
class Names {
	private readonly used = new Set<string>();

	take(id: string): string {
		const base = identifier(id, "item");
		let name = base;
		for (let k = 2; this.used.has(name); k += 1) name = `${base}_${k}`;
		this.used.add(name);
		return name;
	}
}

function identifier(id: string, fallback: string): string {
	const name = id.replace(/[^A-Za-z0-9_]/g, "_");
	if (name === "") return fallback;
	return /^[0-9]/.test(name) ? `_${name}` : name;
}

/** A number as usda text: up to 9 decimals, no -0. */
function num(value: number): string {
	const rounded = Math.round(value * 1e9) / 1e9;
	return String(Object.is(rounded, -0) ? 0 : rounded);
}

function tuple(values: readonly number[]): string {
	return `(${values.map(num).join(", ")})`;
}

function tuples(values: readonly (readonly number[])[]): string {
	return `[${values.map(tuple).join(", ")}]`;
}

/** A double-quoted usda string. */
function text(value: string): string {
	let escaped = "";
	for (const c of value) {
		const code = c.codePointAt(0) as number;
		if (c === "\\") escaped += "\\\\";
		else if (c === '"') escaped += '\\"';
		else if (c === "\n") escaped += "\\n";
		else if (c === "\t") escaped += "\\t";
		else if (code < 0x20 || code === 0x7f) {
			escaped += `\\x${code.toString(16).padStart(2, "0")}`;
		} else escaped += c;
	}
	return `"${escaped}"`;
}

/** An asset path: `@…@`, or `@@@…@@@` when it holds an `@`. */
function assetRef(path: string): string {
	return path.includes("@") ? `@@@${path}@@@` : `@${path}@`;
}

/** Indented usda text. */
class Usda {
	private readonly lines: string[] = [];
	private depth = 0;

	line(value: string): void {
		this.lines.push(value === "" ? "" : `${"    ".repeat(this.depth)}${value}`);
	}

	/** A line that opens a block; with `brace`, the brace on its own line. */
	open(value: string, brace?: string): void {
		this.line(value);
		if (brace !== undefined && brace !== "") this.line(brace);
		this.depth += 1;
	}

	close(value: string): void {
		this.depth -= 1;
		this.line(value);
	}

	toString(): string {
		return `${this.lines.join("\n")}\n`;
	}
}
